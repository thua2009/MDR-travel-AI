    fun get(language: Language): Strings = when (language) {
        Language.VI -> viStrings
        Language.EN -> enStrings
        Language.KO -> koStrings
        Language.JA -> jaStrings
    }

    fun getBadgeText(badge: SmartBadgeType, language: Language): String {
        val s = get(language)
        return when (badge) {
            SmartBadgeType.VERIFIED_LOCAL_PRICE -> s.badgeVerifiedLocalPrice
            SmartBadgeType.SENIOR_STROLLER_FRIENDLY -> s.badgeSeniorStroller
            SmartBadgeType.KID_SAFE_NON_SPICY -> s.badgeKidSafeNonSpicy
            SmartBadgeType.INDOOR_WEATHER_SAFE -> s.badgeIndoorWeatherSafe
        }
    }
